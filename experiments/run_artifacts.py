"""Run artifact layout and IO.

Every completed run writes one self-describing directory::

    experiments/runs/<experiment_id>/<run_id>/
    |-- config.json         the exact experiment configuration, incl. config_hash
    |-- metrics.json        the result schema, including explicit nulls
    |-- environment.json    interpreter, OS, platform, packages, git commit
    |-- dataset_info.json   manifest/split hashes and dataset composition
    `-- README.md           human-readable summary for reviewers

Layout rules
------------
1. **One directory per run.** A run id is never reused, so a directory is immutable
   once written. Re-running overwrites nothing; it produces a new run id.
2. **Self-contained.** A directory can be archived and read months later without
   reference to the repository, because all context is captured inside it.
3. **Generated, not authored.** ``experiments/runs/`` is git-ignored. Result
   *summaries* (markdown, JSON, CSV) are curated into ``reports/`` instead, so the
   repository stores conclusions rather than bulk output.

No run is generated by this module at import time. Callers must invoke
:meth:`RunArtifacts.write` explicitly.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from experiments.results import ExperimentResult
from experiments.schema import ExperimentConfig
from ml.reproducibility.environment import EnvironmentReport

__all__ = [
    "REQUIRED_RUN_FILES",
    "RUN_ARTIFACTS_README_TEMPLATE",
    "RunArtifacts",
    "default_run_id",
    "run_directory",
    "validate_run_directory",
]

REQUIRED_RUN_FILES = (
    "config.json",
    "metrics.json",
    "environment.json",
    "dataset_info.json",
    "README.md",
)

RUN_ARTIFACTS_README_TEMPLATE = """\
# Run `{run_id}`

| Field | Value |
| --- | --- |
| Experiment | `{experiment_id}` |
| Name | {name} |
| Type | {experiment_type} |
| Modality | {modality} |
| Model version | {model_version} |
| Seed | {seed} |
| Run number | {run_number} |
| Training dataset | `{training_dataset}` |
| Validation dataset | `{validation_dataset}` |
| Test dataset | `{test_dataset}` |
| Config hash | `{config_hash}` |
| Evaluated samples | {evaluated_samples} |
| Completed at | {completed_at} |

## Metrics

{metrics_table}

## Datasets

{datasets_table}

## Environment

- Python: {python_version}
- Platform: {platform}
- Git commit: {git_commit}

## Notes

{notes}

---
Generated by `experiments.run_artifacts`. Do not edit by hand: this directory is a
record of one run. Curated summaries belong in `reports/`.
"""


@dataclass(frozen=True, slots=True)
class RunArtifacts:
    """The five artifacts constituting one run record.

    Attributes:
        directory: Destination directory.
        config: The experiment configuration.
        result: The measured result. Metrics that were not measured stay ``None``.
        environment: Captured software environment.
        dataset_info: Dataset composition and content hashes, as a mapping.
    """

    directory: Path
    config: ExperimentConfig
    result: ExperimentResult
    environment: EnvironmentReport
    dataset_info: dict[str, Any]

    def __post_init__(self) -> None:
        if self.config.experiment_id != self.result.experiment_id:
            raise ValueError(
                "config and result disagree on experiment_id: "
                f"{self.config.experiment_id!r} vs {self.result.experiment_id!r}"
            )
        if self.config.seed != self.result.seed:
            raise ValueError(
                f"config and result disagree on seed: {self.config.seed} vs {self.result.seed}"
            )
        if self.config.run_number != self.result.run_number:
            raise ValueError(
                "config and result disagree on run_number: "
                f"{self.config.run_number} vs {self.result.run_number}"
            )

    @property
    def run_id(self) -> str:
        return self.result.run_id

    def _metrics_table(self) -> str:
        rows = ["| Metric | Value |", "| --- | --- |"]
        for name in sorted(self.result.measured_metrics):
            rows.append(f"| {name} | {self.result.value(name)} |")
        for name in sorted(self.result.missing_metrics):
            rows.append(f"| {name} | _not measured_ |")
        return "\n".join(rows)

    def _datasets_table(self) -> str:
        rows = ["| Dataset | Manifest hash |", "| --- | --- |"]
        manifests = self.config.manifests_used
        for name in self.config.all_datasets:
            rows.append(f"| `{name}` | `{manifests.get(name, 'unrecorded')}` |")
        return "\n".join(rows)

    def render_readme(self) -> str:
        """Render the human-readable run summary."""
        notes = "\n".join(f"- {note}" for note in self.result.notes) or "_None recorded._"
        return RUN_ARTIFACTS_README_TEMPLATE.format(
            run_id=self.run_id,
            experiment_id=self.config.experiment_id,
            name=self.config.name,
            experiment_type=self.config.experiment_type.value,
            modality=self.config.modality.value,
            model_version=self.config.model_version,
            seed=self.config.seed,
            run_number=self.config.run_number,
            training_dataset=self.config.training_dataset,
            validation_dataset=self.config.validation_dataset,
            test_dataset=self.config.test_dataset,
            config_hash=self.config.config_hash,
            evaluated_samples=self.result.evaluated_samples,
            completed_at=self.result.completed_at,
            metrics_table=self._metrics_table(),
            datasets_table=self._datasets_table(),
            python_version=self.environment.python_version,
            platform=self.environment.platform,
            git_commit=self.environment.git_commit or "_not a git checkout_",
            notes=notes,
        )

    def write(self, *, overwrite: bool = False) -> Path:
        """Write all five artifacts and return the run directory.

        Args:
            overwrite: Permit writing into a directory that already contains a run.
                ``False`` by default so a completed run is never mutated in place.

        Returns:
            The run directory.

        Raises:
            FileExistsError: If the directory already contains artifacts and
                ``overwrite`` is ``False``.
        """
        self.directory.mkdir(parents=True, exist_ok=True)
        if not overwrite:
            for name in REQUIRED_RUN_FILES:
                if (self.directory / name).exists():
                    raise FileExistsError(
                        f"run artifacts already exist in {self.directory}; "
                        "use a new run_id or pass overwrite=True"
                    )

        payloads: dict[str, str] = {
            "config.json": json.dumps(self.config.to_dict(), indent=2, sort_keys=True) + "\n",
            "metrics.json": self.result.to_json() + "\n",
            "environment.json": self.environment.to_json() + "\n",
            "dataset_info.json": json.dumps(
                self.dataset_info, indent=2, sort_keys=True, default=str
            )
            + "\n",
            "README.md": self.render_readme(),
        }
        for name, content in payloads.items():
            (self.directory / name).write_text(content, encoding="utf-8", newline="\n")
        return self.directory


def default_run_id(
    *,
    seed: int,
    run_number: int,
    timestamp: datetime | str | None = None,
) -> str:
    """Build a run id following ``configs.project.reproducibility.naming_template``.

    The template is ``{module}/{task}/{dataset}/{seed}_{timestamp}``; for a run
    directory the full path form is reduced to a flat, sortable id of
    ``seed{seed}_run{run_number}_{timestamp}``.

    Raises:
        ValueError: If ``timestamp`` is neither a datetime nor an ISO string.
    """
    if isinstance(timestamp, datetime):
        stamp = timestamp.strftime("%Y%m%dT%H%M%SZ")
    elif isinstance(timestamp, str):
        stamp = "".join(char for char in timestamp if char.isalnum())
    else:
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    return f"seed{seed}_run{run_number}_{stamp}"


def run_directory(runs_root: Path | str, experiment_id: str, run_id: str) -> Path:
    """Resolve ``<runs_root>/<experiment_id>/<run_id>``.

    Args:
        runs_root: Typically ``experiments/runs``.
        experiment_id: Validated slug, safe as a directory name.
        run_id: Unique run identifier.

    Returns:
        The resolved directory path. It is not created.

    Raises:
        ValueError: If either identifier contains a path separator or ``..``.
    """
    for name, value in (("experiment_id", experiment_id), ("run_id", run_id)):
        if not value or value in {".", ".."} or "/" in value or "\\" in value:
            raise ValueError(f"{name} must be a single safe path segment, got {value!r}")
    return Path(runs_root) / experiment_id / run_id


def validate_run_directory(directory: Path | str) -> list[str]:
    """Check a run directory against the documented layout.

    Returns:
        A list of problems; empty means the directory conforms. Never raises for
        content problems, so it is usable as a post-hoc integrity check.
    """
    root = Path(directory)
    problems: list[str] = []
    if not root.is_dir():
        return [f"run directory does not exist: {root}"]
    for name in REQUIRED_RUN_FILES:
        if not (root / name).is_file():
            problems.append(f"missing required artifact: {name}")
    for name in ("config.json", "metrics.json", "environment.json", "dataset_info.json"):
        path = root / name
        if path.is_file():
            try:
                json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError as exc:
                problems.append(f"{name} is not valid JSON: {exc.msg}")
    return problems
